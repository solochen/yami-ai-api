// PromptPackByCode 返回指定智能体的提示词包。
func PromptPackByCode(code string) (PromptPack, bool) {
	pack, ok := promptPacks[code]
	return pack, ok
}

// PromptAgentCodes 返回内置提示词智能体的编码列表（按字母序，便于测试与文档）。
func PromptAgentCodes() []string {
	codes := make([]string, 0, len(promptPacks))
	for code := range promptPacks {
		codes = append(codes, code)
	}
	sort.Strings(codes)
	return codes
}
